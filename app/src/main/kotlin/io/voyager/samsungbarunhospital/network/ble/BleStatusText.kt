package io.voyager.samsungbarunhospital.network.ble

/**
 * 블루투스 스택이 돌려주는 숫자 코드를 사람이 읽을 수 있는 말로 바꾼다 (순수 로직).
 *
 * 안드로이드의 광고 실패 콜백·GATT 연결 상태 콜백에는 안드로이드가 정의한 코드 말고도 블루투스 칩의
 * HCI 상태값이 그대로 올라오는 경우가 많다(현장 기록의 "오류코드 12"가 그 예). 이 표는 Bluetooth Core
 * Specification의 "Error Codes"에서 현장에서 볼 만한 것만 옮긴 것이다. 코드는 "무슨 일이 났는지"까지만
 * 알려주고 "왜"는 알려주지 않으므로, 기록에는 그때의 연결 수 같은 정황을 함께 남긴다.
 */
object BleStatusText {

    /** HCI 상태값 중 "동시 연결 한도 초과"를 직접 뜻하는 값. */
    const val HCI_CONNECTION_LIMIT_EXCEEDED = 0x09

    fun hci(code: Int): String? = when (code) {
        0x07 -> "블루투스 칩 메모리 부족"
        0x08 -> "연결 시간 초과(상대가 응답 없음 — 거리가 멀거나 전원이 꺼짐)"
        0x09 -> "동시 연결 한도 초과"
        0x0C -> "지금 상태에서는 허용되지 않는 명령(동시에 연결할 수 있는 수가 찼을 때 주로 발생)"
        0x0D -> "자원 부족으로 거부됨"
        0x11 -> "지원하지 않는 기능"
        0x12 -> "잘못된 설정값"
        0x13 -> "상대가 연결을 끊음"
        0x14 -> "상대가 자원 부족으로 연결을 끊음"
        0x15 -> "상대 기기 전원이 꺼져 연결이 끊김"
        0x16 -> "이 기기가 연결을 끊음"
        0x1F -> "원인이 지정되지 않은 오류"
        0x22 -> "응답 시간 초과"
        0x28 -> "타이밍 문제로 연결 실패"
        0x3A -> "블루투스 칩이 바쁨"
        0x3B -> "받아들일 수 없는 연결 설정"
        0x3E -> "연결을 맺지 못함(상대가 응답하지 않음)"
        else -> null
    }

    /** GATT 연결 상태 콜백의 status. 안드로이드 고유값(133 등)과 HCI 값이 섞여 온다. */
    fun gattStatus(status: Int): String = when (status) {
        0 -> "정상"
        133 -> "연결 실패(안드로이드 일반 오류 — 상대가 멀거나, 연결 자리가 없거나, 블루투스가 불안정)"
        257 -> "연결 실패"
        else -> hci(status) ?: "알 수 없는 상태"
    }
}
